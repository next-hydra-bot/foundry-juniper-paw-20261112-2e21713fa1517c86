export const addressRegions = (
  country: string
): readonly { readonly code: string; readonly label: string }[] => {
  if (country === "US") {
    return usRegions;
  }
  if (country === "CA") {
    return canadaRegions;
  }
  return [];
};

const comparable = (value: string) =>
  value
    .trim()
    .normalize("NFD")
    .replaceAll(/\p{Diacritic}/gu, "")
    .toLowerCase();

/** Accept native codes and human-readable names at the provider boundary. */
export const addressRegionCode = (
  country: string,
  value: string | undefined
): string | undefined => {
  const input = value?.trim();
  if (!input) {
    return undefined;
  }
  const match = addressRegions(country).find(
    ({ code, label }) =>
      comparable(code) === comparable(input) ||
      comparable(label) === comparable(input)
  );
  return match?.code ?? input;
};
